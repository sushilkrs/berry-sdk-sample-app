"""The app's own database (SQLite, data/app.db).

Students and their documents live here: who uploaded what, where the file is stored and how far each
document got in Berry. Berry holds the extracted content; this database is the app's source of truth for
identity, so it knows its own state even when Berry is slow or down.
"""
import sqlite3
import threading
from contextlib import contextmanager
from datetime import datetime, timezone

from . import config

SCHEMA = """
CREATE TABLE IF NOT EXISTS students (
    id                TEXT PRIMARY KEY,         -- student UUID, generated by the app; also the Berry profile id
    full_name         TEXT NOT NULL,
    email             TEXT,
    created_at        TEXT NOT NULL,
    profile_synced_at TEXT,                     -- last successful upsert of the Berry profile
    profile_error     TEXT
);

CREATE TABLE IF NOT EXISTS documents (
    id               TEXT PRIMARY KEY,          -- document UUID, generated by the app
    student_id       TEXT NOT NULL REFERENCES students(id),
    file_name        TEXT NOT NULL,
    file_type        TEXT NOT NULL,             -- MIME type as uploaded
    file_size        INTEGER NOT NULL,          -- bytes
    sha256           TEXT NOT NULL,             -- only compared within one student
    file_path        TEXT NOT NULL,             -- storage/students/<student>/documents/<document>/<name>
    uploaded_at      TEXT NOT NULL,
    status           TEXT NOT NULL,             -- stored | sending | ingested | failed
    berry_record_id  TEXT,                      -- Berry derives it from the file bytes
    fields_filled    INTEGER,
    pages            INTEGER,
    text_field       TEXT,
    ingested_at      TEXT,
    error            TEXT,
    ner_status       TEXT,                      -- requested | done | failed
    ner_requested_at TEXT,
    ner_error        TEXT,
    entity_count     INTEGER,
    UNIQUE (student_id, sha256)
);
CREATE INDEX IF NOT EXISTS documents_student ON documents(student_id);
CREATE INDEX IF NOT EXISTS documents_berry ON documents(berry_record_id);
"""

_lock = threading.Lock()


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


@contextmanager
def _conn():
    con = sqlite3.connect(config.SQLITE_PATH)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    try:
        yield con
        con.commit()
    finally:
        con.close()


def init() -> None:
    with _lock, _conn() as con:
        con.executescript(SCHEMA)


def _insert(table: str, row: dict) -> None:
    cols = ", ".join(row)
    marks = ", ".join("?" for _ in row)
    with _lock, _conn() as con:
        con.execute(f"INSERT INTO {table} ({cols}) VALUES ({marks})", list(row.values()))


def _update(table: str, row_id: str, fields: dict) -> None:
    sets = ", ".join(f"{k} = ?" for k in fields)
    with _lock, _conn() as con:
        con.execute(f"UPDATE {table} SET {sets} WHERE id = ?", [*fields.values(), row_id])


def _one(sql: str, args=()) -> dict | None:
    with _conn() as con:
        r = con.execute(sql, args).fetchone()
    return dict(r) if r else None


def _all(sql: str, args=()) -> list[dict]:
    with _conn() as con:
        return [dict(r) for r in con.execute(sql, args)]


# ---------- students ----------

def insert_student(row: dict) -> None:
    _insert("students", row)


def update_student(student_id: str, **fields) -> None:
    _update("students", student_id, fields)


def get_student(student_id: str) -> dict | None:
    return _one("SELECT * FROM students WHERE id = ?", (student_id,))


def all_students() -> list[dict]:
    return _all("""
        SELECT s.*, COUNT(d.id) AS document_count,
               SUM(d.status = 'ingested') AS ingested_count,
               SUM(d.status IN ('stored', 'sending')) AS pending_count,
               MAX(d.uploaded_at) AS last_upload_at
        FROM students s LEFT JOIN documents d ON d.student_id = s.id
        GROUP BY s.id ORDER BY s.created_at DESC""")


def delete_student(student_id: str) -> None:
    with _lock, _conn() as con:
        con.execute("DELETE FROM documents WHERE student_id = ?", (student_id,))
        con.execute("DELETE FROM students WHERE id = ?", (student_id,))


# ---------- documents ----------

def insert_document(row: dict) -> None:
    _insert("documents", row)


def update_document(document_id: str, **fields) -> None:
    _update("documents", document_id, fields)


def get_document(document_id: str) -> dict | None:
    return _one("SELECT * FROM documents WHERE id = ?", (document_id,))


def documents_of(student_id: str) -> list[dict]:
    return _all("SELECT * FROM documents WHERE student_id = ? ORDER BY uploaded_at DESC", (student_id,))


def find_duplicate(student_id: str, sha256: str) -> dict | None:
    """Same bytes already uploaded by THIS student. Other students are never compared."""
    return _one("SELECT * FROM documents WHERE student_id = ? AND sha256 = ?", (student_id, sha256))


def sharing(berry_record_id: str, exclude_document_id: str = "") -> list[dict]:
    """Other documents (any student) that Berry stored on the same record, because the bytes are identical."""
    return _all("""
        SELECT d.id, d.student_id, d.file_name, s.full_name AS student_name
        FROM documents d JOIN students s ON s.id = d.student_id
        WHERE d.berry_record_id = ? AND d.id != ?""", (berry_record_id, exclude_document_id))


def delete_document(document_id: str) -> None:
    with _lock, _conn() as con:
        con.execute("DELETE FROM documents WHERE id = ?", (document_id,))
